
const { onCall, HttpsError } = require('firebase-functions/v2/https')
const { defineSecret } = require('firebase-functions/params')
const logger = require('firebase-functions/logger')
const sgMail = require('@sendgrid/mail')
const PDFDocument = require('pdfkit')

// Firebase Secret Manager
const sendgridApiKey = defineSecret('SENDGRID_API_KEY')

// IMPORTANT: Replace with your verified SendGrid sender email
const SENDER_EMAIL = 'thirithaw.work@gmail.com'

// Generate a PDF in memory
const generateImpactPDF = (name) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50 })
    const chunks = []

    doc.on('data', (chunk) => chunks.push(chunk))
    doc.on('error', reject)
    doc.on('end', () => resolve(Buffer.concat(chunks)))

    doc.fontSize(22).text('EMITRAIL', { align: 'center' })
    doc.moveDown()
    doc.fontSize(17).text('Climate Impact Summary', {
      align: 'center',
    })

    doc.moveDown(2)
    doc.fontSize(11)
    doc.text(`Prepared for: ${name}`)
    doc.text(`Report date: ${new Date().toLocaleDateString('en-AU')}`)

    doc.moveDown()
    doc.fontSize(14).text('Your Current Dashboard Summary')
    doc.moveDown(0.5)

    doc.fontSize(11)
    doc.text('Active distance: 0 km logged')
    doc.text('Sustainable trips: 0 journeys')
    doc.text('Emissions avoided: 0.0 kg CO2 vs car')
    doc.text('Badges earned: 0 milestones')

    doc.moveDown(2)
    doc.fontSize(10).text(
      'Note: Emitrail journey tracking is not yet connected to ' +
      'persistent travel records. These values represent the ' +
      'current dashboard placeholders.',
    )

    doc.moveDown(2)
    doc.text('Generated by Emitrail', { align: 'center' })

    doc.end()
  })
}

// Firebase callable function
exports.sendImpactReport = onCall(
  {
    region: 'us-central1',
    secrets: [sendgridApiKey],
    maxInstances: 2,
    timeoutSeconds: 60,
    memory: '256MiB',
    enforceAppCheck: false,
  },
  async (request) => {
    // Require Firebase Authentication
    if (!request.auth) {
      throw new HttpsError(
        'unauthenticated',
        'Please log in before emailing your report.',
      )
    }

    // Only send reports to the authenticated user's verified email
    const recipientEmail = request.auth.token.email

    if (!recipientEmail || !request.auth.token.email_verified) {
      throw new HttpsError(
        'failed-precondition',
        'Please verify your Firebase email address first.',
      )
    }

    const name = String(
      request.auth.token.name || recipientEmail,
    ).slice(0, 100)

    try {
      const pdfBuffer = await generateImpactPDF(name)

      sgMail.setApiKey(sendgridApiKey.value())

      await sgMail.send({
        to: recipientEmail,
        from: SENDER_EMAIL,
        subject: 'Your Emitrail Climate Impact Report',
        text:
          `Hello ${name},\n\n` +
          'Your Emitrail Climate Impact Summary is attached as a PDF.\n\n' +
          'Regards,\nEmitrail',
        attachments: [
          {
            content: pdfBuffer.toString('base64'),
            filename: 'Emitrail_Climate_Impact_Report.pdf',
            type: 'application/pdf',
            disposition: 'attachment',
          },
        ],
      })

      logger.info('Impact report email accepted by SendGrid', {
        uid: request.auth.uid,
      })

      return {
        success: true,
        message: 'Your report has been sent to your email address.',
      }
    } catch (error) {
      logger.error('Failed to send impact report', {
        uid: request.auth.uid,
        statusCode: error.code,
      })

      throw new HttpsError(
        'internal',
        'Unable to send the report. Please try again later.',
      )
    }
  },
)
