
const { onCall, HttpsError } = require('firebase-functions/v2/https')
const { defineSecret } = require('firebase-functions/params')
const logger = require('firebase-functions/logger')
const sgMail = require('@sendgrid/mail')
const PDFDocument = require('pdfkit')

// Firebase Admin SDK for accessing Firestore securely
const admin = require('firebase-admin')

admin.initializeApp()

const db = admin.firestore()

// Firebase Secret Manager
const sendgridApiKey = defineSecret('SENDGRID_API_KEY')

// Verified SendGrid sender
const SENDER_EMAIL = 'thirithaw.work@gmail.com'

// --------------------------------------------------
// Retrieve the authenticated user's journey data
// --------------------------------------------------

const getJourneySummary = async (uid) => {
  const snapshot = await db
    .collection('journeys')
    .where('userId', '==', uid)
    .get()

  let totalDistance = 0
  let totalEmissionsSaved = 0

  const journeys = snapshot.docs.map((document) => {
    const data = document.data()

    const distanceKm = Number(data.distanceKm || 0)
    const co2SavedKg = Number(data.co2SavedKg || 0)

    totalDistance += distanceKm
    totalEmissionsSaved += co2SavedKg

    let date = 'Unknown'

    if (data.date && typeof data.date.toDate === 'function') {
      date = data.date.toDate().toLocaleDateString('en-AU')
    }

    return {
      date,
      mode: String(data.mode || 'Unknown'),
      distanceKm,
      co2SavedKg,
    }
  })

  return {
    totalDistance,
    totalTrips: journeys.length,
    totalEmissionsSaved,
    journeys,
  }
}

// --------------------------------------------------
// Generate PDF using real Firestore journey data
// --------------------------------------------------

const generateImpactPDF = (name, summary) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50 })
    const chunks = []

    doc.on('data', (chunk) => chunks.push(chunk))
    doc.on('error', reject)
    doc.on('end', () => resolve(Buffer.concat(chunks)))

    doc.fontSize(22).text('EMITRAIL', { align: 'center' })
    doc.moveDown()

    doc.fontSize(17).text('Climate Impact Summary', {
      align: 'center',
    })

    doc.moveDown(2)

    doc.fontSize(11)
    doc.text(`Prepared for: ${name}`)
    doc.text(`Report date: ${new Date().toLocaleDateString('en-AU')}`)

    doc.moveDown()
    doc.fontSize(14).text('Your Current Dashboard Summary')
    doc.moveDown(0.5)

    doc.fontSize(11)

    doc.text(
      `Active distance: ${summary.totalDistance.toFixed(1)} km logged`,
    )

    doc.text(
      `Sustainable trips: ${summary.totalTrips} journeys`,
    )

    doc.text(
      `Emissions avoided: ${summary.totalEmissionsSaved.toFixed(2)} kg CO2 vs car`,
    )

    doc.text('Badges earned: 0 milestones')

    doc.moveDown(2)

    // --------------------------------------------------
    // Journey history
    // --------------------------------------------------

    doc.fontSize(14).text('Your Logged Journeys')
    doc.moveDown(0.5)

    if (summary.journeys.length === 0) {
      doc.fontSize(11).text(
        'You have not logged any sustainable journeys yet.',
      )
    } else {
      doc.fontSize(10)

      summary.journeys.forEach((journey, index) => {
        doc.text(
          `${index + 1}. ${journey.date} | ${journey.mode}`,
        )

        doc.text(
          `   Distance: ${journey.distanceKm.toFixed(1)} km | ` +
          `CO2 saved: ${journey.co2SavedKg.toFixed(2)} kg`,
        )

        doc.moveDown(0.5)
      })
    }

    doc.moveDown(2)

    doc.fontSize(9).text(
      'Note: Emissions avoided are estimates calculated by ' +
      'comparing logged journeys against equivalent car travel.',
    )

    doc.moveDown(2)

    doc.fontSize(10).text(
      'Generated by Emitrail',
      { align: 'center' },
    )

    doc.end()
  })
}

// --------------------------------------------------
// BR D.2 - Firebase Callable Function
// --------------------------------------------------

exports.sendImpactReport = onCall(
  {
    region: 'us-central1',
    secrets: [sendgridApiKey],
    maxInstances: 2,
    timeoutSeconds: 60,
    memory: '256MiB',
    enforceAppCheck: false,
  },
  async (request) => {
    // Require Firebase Authentication
    if (!request.auth) {
      throw new HttpsError(
        'unauthenticated',
        'Please log in before emailing your report.',
      )
    }

    // Send only to the authenticated user's verified email
    const recipientEmail = request.auth.token.email

    if (!recipientEmail || !request.auth.token.email_verified) {
      throw new HttpsError(
        'failed-precondition',
        'Please verify your Firebase email address first.',
      )
    }

    const name = String(
      request.auth.token.name || recipientEmail,
    ).slice(0, 100)

    try {
      // Retrieve real journey records from Firestore
      const summary = await getJourneySummary(request.auth.uid)

      logger.info('Journey summary retrieved', {
        uid: request.auth.uid,
        totalTrips: summary.totalTrips,
      })

      // Generate PDF containing the real dashboard totals
      const pdfBuffer = await generateImpactPDF(name, summary)

      // Send PDF attachment through SendGrid
      sgMail.setApiKey(sendgridApiKey.value())

      await sgMail.send({
        to: recipientEmail,
        from: SENDER_EMAIL,
        subject: 'Your Emitrail Climate Impact Report',
        text:
          `Hello ${name},\n\n` +
          'Your Emitrail Climate Impact Summary is attached as a PDF.\n\n' +
          'Regards,\nEmitrail',
        attachments: [
          {
            content: pdfBuffer.toString('base64'),
            filename: 'Emitrail_Climate_Impact_Report.pdf',
            type: 'application/pdf',
            disposition: 'attachment',
          },
        ],
      })

      logger.info('Impact report email accepted by SendGrid', {
        uid: request.auth.uid,
      })

      return {
        success: true,
        message: 'Your report has been sent to your email address.',
      }
    } catch (error) {
      logger.error('Failed to send impact report', {
        uid: request.auth.uid,
        message: error.message,
      })

      throw new HttpsError(
        'internal',
        'Unable to send the report. Please try again later.',
      )
    }
  },
)
